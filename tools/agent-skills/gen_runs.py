def page_title(text, limit=60):
    full = f"{text} | Skillsmith by Caffeinity"
    return full if len(full) <= limit else text


def ul(items, cls):
    if not items:
        return ""
    return (f'<ul class="rn-list {cls}">' + "".join(f"<li>{inline(i)}</li>" for i in items) + "</ul>")


# ---------------------------------------------------------------- one skill's page

def run_numbers(run):
    rows = [("Verdict", badge(run["verdict"]) + f"<small>{esc(score_text(run))} against the rubric</small>"),
            ("Ran on", esc(human_date(run["date"]))),
            ("Cost", esc(money(run["cost"])) + "<small>the agent's run, as Claude Code reported it</small>"),
            ("Time", esc(duration(run["seconds"]))),
            ("Turns", esc(run["turns"] if run["turns"] is not None else "not recorded")
             + (f"<small>{esc(run['tool_calls'])} tool calls</small>" if run["tool_calls"] is not None else ""))]
    if run.get("model"):
        rows.append(("Model", esc(run["model"].capitalize())))
    return ('<dl class="rn-nums">' + "".join(f"<div><dt>{k}</dt><dd>{v}</dd></div>" for k, v in rows)
            + "</dl>")


def run_article(run, title):
    parts = [f'<article id="{anchor(run)}" class="rn-run">']
    parts.append(f'<section class="rn-numsec" aria-label="The run in numbers"><div class="wrap">{run_numbers(run)}</div></section>')

    task = [f'<h2 id="{anchor(run)}-task">The task.</h2>',
            f"<p><b>Target:</b> {inline(run['target'])}</p>"]
    if run["prompt"]:
        task.append(f'<p>The prompt {esc(title)} was given, word for word:</p><pre class="rn-pre">{esc(run["prompt"])}</pre>')
    setup = []
    if run["setup"]:
        setup.append(run["setup"].rstrip(".") + ".")
    if run["denied"]:
        setup.append("Pushes, releases, deploys and outbound submissions were denied for the run.")
    if setup:
        task.append(f'<p class="rn-note">{esc(" ".join(setup))}</p>')
    parts.append(f'<section class="tone rn-body" aria-labelledby="{anchor(run)}-task"><div class="wrap">{"".join(task)}</div></section>')

    graded = [f'<h2 id="{anchor(run)}-graded">How it was graded.</h2>']
    if run["rubric"]:
        graded.append("<p>The run was judged against this rubric:</p>" + ul(run["rubric"], "rubric"))
    if run["checks"]:
        graded.append('<p style="margin-top:28px">And these hard checks, which pass or fail on their own:</p>'
                      '<ul class="rn-list">' + "".join(
                          f'<li class="{"ok" if c.get("ok") else "no"}">{inline(c.get("desc", ""))}'
                          + (f' <span class="rn-note">({inline(c["detail"])})</span>' if c.get("detail") and c.get("detail") != c.get("desc") else "")
                          + "</li>" for c in run["checks"]) + "</ul>")
    parts.append(f'<section class="rn-body" aria-labelledby="{anchor(run)}-graded"><div class="wrap">{"".join(graded)}</div></section>')

    cols = []
    if run["met"]:
        cols.append(f"<div><h2>What it got right.</h2>{ul(run['met'], 'met')}</div>")
    if run["missed"]:
        cols.append(f"<div><h2>What it missed.</h2>{ul(run['missed'], 'missed')}</div>")
    if cols:
        parts.append(f'<section class="rn-body" aria-label="Met and missed"><div class="wrap rn-cols">{"".join(cols)}</div></section>')

    if run["defects"]:
        parts.append(f'<section class="tone rn-body" aria-labelledby="{anchor(run)}-defects"><div class="wrap">'
                     f'<h2 id="{anchor(run)}-defects">What the run showed is wrong with the skill.</h2>'
                     f'<p>Problems the grader put down to the skill itself, not to the run\'s setup. '
                     f'Each one goes on the fix list for the next version.</p>{ul(run["defects"], "defects")}</div></section>')

    ev = [f'<h2 id="{anchor(run)}-ev">The evidence.</h2>',
          "<p>Everything the run left behind. Nothing here was edited after the run.</p>"]
    if run["steps"]:
        ev.append(f'<details><summary>Every step it took ({len(run["steps"])})</summary><ol>'
                  + "".join(f"<li>{esc(s)}</li>" for s in run["steps"]) + "</ol></details>")
    if run["truth"]:
        ev.append('<details><summary>The known answer it was checked against</summary>'
                  f'<pre class="rn-pre">{esc(run["truth"])}</pre></details>')
    if run["output"]:
        output = run["output"]
        cut = len(output) > OUTPUT_LIMIT
        if cut:
            output = output[:OUTPUT_LIMIT].rstrip() + "\n…"
        ev.append('<details><summary>Its final answer, as written</summary>'
                  f'<pre class="rn-pre">{esc(output)}</pre>'
                  + (f'<p class="rn-note">Cut for length. <a href="{BLOB}{esc(run["dir"])}/output.md">Read the whole answer</a>.</p>' if cut else "")
                  + "</details>")
    if run["files"]:
        ev.append(f'<details><summary>Files it wrote ({len(run["files"])})</summary><ol>'
                  + "".join(f"<li>{esc(f)}</li>" for f in run["files"]) + "</ol></details>")
    links = [f'<a href="{BLOB}{esc(run["dir"])}/README.md">Full report</a>']
    if run["has_transcript"]:
        links.append(f'<a href="{BLOB}{esc(run["dir"])}/transcript.jsonl">Transcript</a>')
    links.append(f'<a href="{BLOB}{esc(run["dir"])}/verdict.json">Verdict as data</a>')
    if run["has_files"]:
        links.append(f'<a href="{TREE}{esc(run["dir"])}/files">Files it wrote</a>')
    ev.append('<p class="rn-links">' + "".join(links) + "</p>")
    parts.append(f'<section class="rn-body rn-ev" aria-labelledby="{anchor(run)}-ev"><div class="wrap">{"".join(ev)}</div></section>')
    parts.append("</article>")
    return "\n".join(parts)


def render_skill(skill, runs, manifest):
    entries = entries_by_name(manifest)
    entry = entries.get(skill) or {}
    title = title_of(skill, entries)
    latest = runs[0]
    canonical = f"{skilllib.SITE}/{OUT}/{skill}/"
    label = "test run" if len(runs) == 1 else "test runs"
    description = meta_description(f"{latest['verdict']}, {score_text(latest)}: {latest['summary']}")
    link = page_link(skill, entries)
    crumbs = (f'<p class="crumbs"><a href="/{OUT}/">Test runs</a>'
              + (f'<a href="{link}">{esc(title)}</a>' if link else "")
              + f"<span>{esc(human_date(latest['date']))}</span></p>")
    hero = (f'<header class="page-hero rn-hero">\n  <div class="wrap">\n    {crumbs}\n'
            f"    <h1>How {esc(title)} did on a real task.</h1>\n"
            f"    <p class=\"lead\">{inline(latest['summary'])}</p>\n"
            f"    <p class=\"rn-meta\">{badge(latest['verdict'])}<span>{esc(score_text(latest))}</span>"
            f"<span>{esc(human_date(latest['date']))}</span><span>{esc(money(latest['cost']))}</span>"
            f"<span>{esc(duration(latest['seconds']))}</span></p>\n  </div>\n</header>")
    earlier = ""
    if len(runs) > 1:
        earlier = ('<section class="rn-body" aria-label="All runs"><div class="wrap"><h2>Every run of this skill.</h2>'
                   '<ul class="rn-list rubric">' + "".join(
                       f'<li><a href="#{anchor(r)}">{esc(human_date(r["date"]))}</a>: {esc(r["verdict"])}, '
                       f'{esc(score_text(r))}</li>' for r in runs) + "</ul></div></section>")
    install = entry.get("install")
    tail = ['<section class="roast" aria-labelledby="next-h">\n  <div class="wrap">',
            '    <h2 id="next-h">Try it on your own task.</h2>']
    if install:
        tail.append(f'    <div class="console"><pre>{esc(install)}</pre>'
                    f'<button class="btn btn-accent" type="button" data-copy="{esc(install)}">Copy</button></div>')
    more = []
    if link:
        more.append(f'<a href="{link}">What {esc(title)} does and what it is not for</a>')
    more.append(f'<a href="/{OUT}/">Every test run</a>')
    more.append(f'<a href="{RUNNER}">How runs are set up</a>')
    tail.append('    <p class="alt">' + " · ".join(more) + ".</p>")
    tail.append("  </div>\n</section>")
    return (head_html(page_title(f"{title}: {label}"), description, canonical)
            + hero + "\n" + earlier + "\n" + "\n".join(run_article(r, title) for r in runs) + "\n"
            + "\n".join(tail) + "\n</main>\n\n" + FOOTER)


