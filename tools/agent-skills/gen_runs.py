def expected_pages(root, manifest):
    runs = load_runs(root)
    root = Path(root)
    yield root / OUT / "index.html", render_index(runs, manifest)
    for skill, items in runs.items():
        yield root / OUT / skill / "index.html", render_skill(skill, items, manifest)


def stale_extras(root, runs):
    """Generated run pages whose runs are gone."""
    base = Path(root) / OUT
    if not base.is_dir():
        return []
    return [p for p in base.glob("*/index.html") if p.parent.name not in runs
            and MARKER in p.read_text(encoding="utf-8")]


def main(argv=None):
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--root", default=".")
    args = parser.parse_args(argv)
    root = Path(args.root)
    manifest = skilllib.load_manifest(root)
    skilllib.validate_manifest(manifest)
    pages = list(expected_pages(root, manifest))
    extras = stale_extras(root, load_runs(root))
    if args.write:
        for path, text in pages:
            path.parent.mkdir(parents=True, exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
        for path in extras:
            path.unlink()
            path.parent.rmdir() if not any(path.parent.iterdir()) else None
        print(f"run pages written: {len(pages)}" + (f", removed {len(extras)}" if extras else ""))
        return 0
    stale = []
    for path, expected in pages:
        actual = path.read_text(encoding="utf-8") if path.exists() else None
        if actual != expected:
            stale.append(path.relative_to(root).as_posix())
            if actual is not None:
                diff = difflib.unified_diff(actual.splitlines(), expected.splitlines(),
                                            fromfile="committed", tofile="generated", lineterm="")
                print("\n".join(list(diff)[:20]))
    stale += [p.relative_to(root).as_posix() for p in extras]
    if stale:
        print(f"run pages are stale: {', '.join(stale)}; run gen_runs.py --write", file=sys.stderr)
        return 1
    print(f"{len(pages)} run pages are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
