def esc(value):
    return html.escape(str(value), quote=True)


def inline(text):
    """Escape a line of the run reports, keeping their `code` spans."""
    parts = str(text).split("`")
    return "".join(f"<code>{esc(p)}</code>" if i % 2 else esc(p) for i, p in enumerate(parts))


def meta_description(text, limit=155):
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    cut = text[:limit]
    return cut[:cut.rfind(" ")].rstrip(" ,;:-") + "…"


# ---------------------------------------------------------------- reading the run folders

def split_sections(text):
    """The README's own sections. The final output is last and may carry ## headings of its
    own, so everything after "## Final output" belongs to it, and fenced blocks never start
    a section."""
    head, sections, current, fence = [], {}, None, False
    for line in text.splitlines():
        if line.startswith("```"):
            fence = not fence
        title = line[3:].strip() if line.startswith("## ") and not fence else None
        if title in SECTIONS and current != "Final output" and title not in sections:
            current = title
            sections[current] = []
            continue
        (sections[current] if current else head).append(line)
    return "\n".join(head), {k: "\n".join(v).strip("\n") for k, v in sections.items()}


def fenced(text):
    match = re.search(r"^```[^\n]*\n(.*?)^```", text or "", re.S | re.M)
    return match.group(1).rstrip("\n") if match else ""


def bullets(text):
    items = []
    for line in (text or "").splitlines():
        m = re.match(r"^\s*(?:[-*]|\d+\.)\s+(.*)$", line)
        if m:
            items.append(m.group(1).strip())
        elif items and line.startswith("  ") and line.strip():
            items[-1] += " " + line.strip()
    return items


def step_text(item):
    return item[1:-1] if item.startswith("`") and item.endswith("`") and item.count("`") == 2 else item


def how_it_ran(head):
    """The run's setup sentence from the README header, e.g. 'Run headless on sonnet in a clean
    project with only this skill installed'."""
    match = re.search(r"(Run headless[^(.]*)", head)
    return match.group(1).strip() if match else ""


def load_run(folder, root):
    verdict = json.loads((folder / "verdict.json").read_text(encoding="utf-8"))
    readme = folder / "README.md"
    head, sections = split_sections(readme.read_text(encoding="utf-8")) if readme.is_file() else ("", {})
    truth = folder / "truth.txt"
    output = folder / "output.md"
    rel = folder.relative_to(root).as_posix()
    checks = verdict.get("checks") or []
    if not checks:
        checks = [{"desc": re.sub(r"^[✓✗]\s*", "", b), "ok": b.startswith("✓")}
                  for b in bullets(sections.get("Hard checks"))]
    return {
        "skill": verdict["skill"],
        "date": verdict["date"],
        "verdict": verdict["verdict"],
        "score": verdict.get("score"),
        "target": verdict.get("target", ""),
        "summary": " ".join(verdict.get("summary", "").split()),
        "checks": checks,
        "met": verdict.get("met") or [],
        "missed": verdict.get("missed") or [],
        "defects": verdict.get("skill_defects") or [],
        "cost": verdict.get("cost_usd"),
        "turns": verdict.get("turns"),
        "seconds": verdict.get("seconds"),
        "tool_calls": verdict.get("tool_calls"),
        "model": verdict.get("model"),
        "prompt": fenced(sections.get("Prompt")),
        "rubric": bullets(sections.get("Rubric")),
        "steps": [step_text(s) for s in bullets(sections.get("What it did"))],
        "truth": truth.read_text(encoding="utf-8").rstrip() if truth.is_file() else fenced(sections.get("Ground truth")),
        "output": output.read_text(encoding="utf-8").rstrip() if output.is_file() else sections.get("Final output", ""),
        "files": verdict.get("files") or [],
        "setup": how_it_ran(head),
        "denied": "Pushes, releases, deploys and outbound submissions were denied" in head,
        "dir": rel,
        "has_transcript": (folder / "transcript.jsonl").is_file(),
        "has_files": (folder / "files").is_dir(),
    }


def load_runs(root):
    """{skill: [run, newest first]} for every reports/runs/<date>/<skill>/verdict.json."""
    root = Path(root)
    runs = {}
    for path in sorted((root / RUNS).glob("*/*/verdict.json")):
        run = load_run(path.parent, root)
        runs.setdefault(run["skill"], []).append(run)
    for items in runs.values():
        items.sort(key=lambda r: r["date"], reverse=True)
    return dict(sorted(runs.items()))


def run_skills(root):
    """Skills that have a page under /runs/."""
    return list(load_runs(root))


def anchor(run):
    return f"run-{run['date']}"


def run_url(skill, date=None):
    return f"/{OUT}/{skill}/" + (f"#run-{date}" if date else "")


# ---------------------------------------------------------------- formatting

def money(value):
    if value is None:
        return "not recorded"
    return "under $0.01" if value < 0.01 else f"${value:,.2f}"


def duration(seconds):
    if seconds is None:
        return "not recorded"
    seconds = int(round(seconds))
    if seconds < 60:
        return f"{seconds} s"
    minutes, rest = divmod(seconds, 60)
    return f"{minutes} min" + (f" {rest} s" if rest else "")


def badge(verdict):
    return f'<span class="rn-verdict {esc(verdict.lower())}">{esc(verdict)}</span>'


def score_text(run):
    return f"{run['score']}/10" if run.get("score") is not None else "not scored"


def entries_by_name(manifest):
    return {s["name"]: s for s in manifest["skills"]}


def title_of(skill, entries):
    entry = entries.get(skill)
    return entry["title"] if entry and entry.get("title") else skill


def page_link(skill, entries):
    entry = entries.get(skill)
    return f"/{skill}/" if entry and entry.get("page") != "none" else None


