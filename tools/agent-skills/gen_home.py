"""Rewrite the marked regions of the hub pages, and the workflow pages, from site/skills.json.

The hub pages are hand-written shells (the homepage, /skills/, /mods/, /workflows/); only the
text between <!-- gen:NAME:start --> and <!-- gen:NAME:end --> is generated, and a page carries
only the regions it wants. Each workflow also gets a fully generated page at /workflows/<slug>/.
"""

import argparse
import difflib
import html
import json
import re
import shutil
import sys
from pathlib import Path

import skilllib

HUB_PAGES = ["index.html", "skills/index.html", "mods/index.html", "workflows/index.html"]
FLOW_TEMPLATE = Path(__file__).resolve().parent / "templates" / "workflow-page.html"
FLOW_MARKER = "<!-- generated by gen_home.py from site/skills.json -->"
REGION_RE = re.compile(r"<!-- gen:([a-z-]+):start -->")
HUB_DESCRIPTION = ("Tested agent skills for Claude Code, Codex, Cursor and any agent that reads a "
                   "SKILL.md, chained into workflows: build a skill, get found, launch safely, rank, "
                   "get hired, decide.")


def esc(value):
    return html.escape(str(value), quote=False)


def attr(value):
    return html.escape(str(value), quote=True)


def visible(manifest):
    ids = {group["id"]: group["order"] for group in manifest["groups"]}
    skills = [s for s in manifest["skills"] if s["page"] != "none"]
    return sorted(skills, key=lambda s: (ids[s["group"]], s["order"]))


def skills_only(manifest):
    return [s for s in visible(manifest) if s.get("kind") != "mod"]


def mods_only(manifest):
    return [s for s in visible(manifest) if s.get("kind") == "mod"]


def featured(manifest):
    return sorted((s for s in visible(manifest) if s.get("featured")), key=lambda s: s["featured"])


def install_of(skill):
    return skill.get("install") or f"npx skills add {skill['repo']}"


def card(skill):
    name = esc(skill["name"])
    repo = attr(f"https://github.com/{skill['repo']}")
    search = attr(" ".join([skill["name"], skill["title"], skill["tag"], skill["blurb"]]).lower())
    chips = [esc(skill["tag"])]
    if skill.get("chain"):
        chips.append("chain")
    if skill.get("kind") == "mod":
        chips.append("Claude Code mod")
    if skill.get("tested"):
        chips.append("tested " + esc(human_date(skill["tested"]["date"])))
    chip_html = "".join(f'<span class="chip{" chip-hot" if c != chips[0] else ""}">{c}</span>'
                        for c in chips)
    return [
        f'      <article class="skill" id="{name}" data-search="{search}">',
        f'        <p class="chips">{chip_html}</p>',
        f'        <h3><a href="/{name}/">{esc(skill["title"])}</a></h3>',
        f'        <p class="sk-blurb">{esc(skill["blurb"])}</p>',
        f'        <p class="sk-stats">{esc(skill["stats"])}</p>',
        f'        <code class="sk-install">{esc(install_of(skill))}</code>',
        '        <p class="sk-links">',
        f'          <a href="/{name}/">Install page</a>',
        f'          <a href="{repo}" target="_blank" rel="noopener">Source</a>',
        '        </p>',
        '      </article>',
    ]


def count_label(cards):
    mods = sum(1 for s in cards if s.get("kind") == "mod")
    skills = len(cards) - mods
    parts = [f"{skills} skill" + ("" if skills == 1 else "s")] if skills else []
    if mods:
        parts.append(f"{mods} mod" + ("" if mods == 1 else "s"))
    return " and ".join(parts)


def human_date(iso):
    year, month, day = iso.split("-")
    months = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
    return f"{int(day)} {months[int(month) - 1]} {year}"


def groups_with(manifest, cards):
    return [g for g in sorted(manifest["groups"], key=lambda g: g["order"])
            if any(s["group"] == g["id"] for s in cards)]


def render_skills(manifest):
    """The catalogue on /skills/: skills by group. Mods have their own page."""
    cards = skills_only(manifest)
    lines = []
    for group in groups_with(manifest, cards):
        rows = [s for s in cards if s["group"] == group["id"]]
        gid = esc(group["id"])
        lines += [f'    <section class="sk-group" id="{gid}" aria-labelledby="{gid}-h">',
                  '      <div class="sk-head">',
                  f'        <h2 id="{gid}-h">{esc(group["title"])}</h2>',
                  f'        <p>{count_label(rows)} · {esc(group["descriptor"])}</p>',
                  '      </div>',
                  '      <div class="sk-grid">']
        for skill in rows:
            lines.extend("  " + line for line in card(skill))
        lines += ['      </div>', '    </section>', '']
    return "\n".join(lines)


def render_jump(manifest):
    return "\n".join(f'      <a href="#{esc(g["id"])}">{esc(g["title"])}</a>'
                     for g in groups_with(manifest, skills_only(manifest)))


def render_mods(manifest):
    lines = ['    <div class="sk-grid">']
    for skill in mods_only(manifest):
        lines.extend("  " + line for line in card(skill))
    lines.append('    </div>')
    return "\n".join(lines)


def render_wall(manifest):
    """Two drifting rows of small cards: every skill and mod at a glance, linking to its page.

    Each row holds its cards twice so the CSS loop is seamless; the copy is hidden from
    assistive tech and the tab order.
    """
    cards = visible(manifest)
    rows = [cards[0::2], cards[1::2]]
    lines = ['<div class="wall" aria-label="Every skill and mod">']
    for i, row in enumerate(rows):
        lines.append(f'  <div class="wall-row{" wall-rev" if i else ""}"><div class="wall-track">')
        for copy in (False, True):
            hide = ' aria-hidden="true" tabindex="-1"' if copy else ""
            for s in row:
                lines.append(f'    <a class="wcard" href="/{esc(s["name"])}/"{hide}><b>{esc(s["name"])}</b>'
                             f'<code>{esc(s["repo"])}</code></a>')
        lines.append('  </div></div>')
    lines.append('</div>')
    return "\n".join(lines)


def flow_skills(flow):
    return [n for step in flow["steps"] for n in step["skills"]]


def render_workflows(manifest):
    lines = []
    for flow in manifest.get("workflows", []):
        url = f'/workflows/{esc(flow["slug"])}/'
        lines.append(f'    <article class="flow" id="{esc(flow["id"])}">')
        lines.append(f'      <p class="flow-id">{esc(skilllib.brew_label(flow))}</p>')
        lines.append(f'      <h3><a href="{url}">{esc(flow["title"])}</a></h3>')
        lines.append(f'      <p class="flow-sum">{esc(flow["summary"])}</p>')
        lines.append('      <ol class="flow-steps">')
        for step in flow["steps"]:
            links = " <span class=\"or\">or</span> ".join(
                f'<a href="/{esc(n)}/">{esc(n)}</a>' for n in step["skills"])
            opt = ' <span class="opt">optional</span>' if step.get("optional") else ""
            lines.append(f'        <li>{links}{opt}</li>')
        lines.append('      </ol>')
        if flow.get("note"):
            lines.append(f'      <p class="flow-note">{esc(flow["note"])}</p>')
        lines.append(f'      <a class="flow-go" href="{url}">Open the workflow</a>')
        lines.append('    </article>')
    return "\n".join(lines)


def render_outcomes(manifest):
    """The homepage's front door: one card per workflow, named by its outcome."""
    lines = []
    for flow in manifest.get("workflows", []):
        n = len(set(flow_skills(flow)))
        lines += [f'      <a class="outcome" href="/workflows/{esc(flow["slug"])}/">',
                  f'        <b>{esc(flow["title"])}</b>',
                  f'        <span>{n} skill{"" if n == 1 else "s"} · {esc(skilllib.brew_label(flow))}</span>',
                  '      </a>']
    return "\n".join(lines)


def render_flagships(manifest):
    """Up to three featured skills, each with the real run that earned it the spot."""
    lines = []
    for skill in featured(manifest):
        tested = skill["tested"]
        name = esc(skill["name"])
        evidence = attr(tested["evidence"])
        external = ' target="_blank" rel="noopener"' if tested["evidence"].startswith("https://") else ""
        lines += [f'      <article class="flag">',
                  f'        <p class="flag-tag">{esc(skill["tag"])}</p>',
                  f'        <h3><a href="/{name}/">{esc(skill["title"])}</a></h3>',
                  f'        <p class="flag-blurb">{esc(skill["blurb"])}</p>',
                  f'        <p class="flag-run"><b>Shown working, {esc(human_date(tested["date"]))}, '
                  f'on {esc(tested["target"])}.</b> {esc(tested["result"])} '
                  f'<a href="{evidence}"{external}>See the run</a></p>',
                  f'        <button class="cmd" type="button" data-copy="{attr(install_of(skill))}" '
                  f'aria-label="Copy the install command for {name}"><span>{esc(install_of(skill))}</span>'
                  f'<span class="copy" aria-hidden="true">Copy</span></button>',
                  '      </article>']
    return "\n".join(lines)


def render_stats(manifest):
    cards = visible(manifest)
    groups = len(groups_with(manifest, cards))
    flows = len(manifest.get("workflows", []))
    return (f'<p class="stats">{count_label(cards)} · {flows} workflow{"" if flows == 1 else "s"} · '
            f'{groups} {"category" if groups == 1 else "categories"} · 0 API keys</p>')


def item_list(name, path, cards):
    items = [{"@type": "ListItem", "position": i, "name": s["name"],
              "url": f"{skilllib.SITE}/{s['name']}/"} for i, s in enumerate(cards, 1)]
    data = {"@context": "https://schema.org", "@type": "ItemList", "name": name,
            "url": f"{skilllib.SITE}{path}", "numberOfItems": len(items), "itemListElement": items}
    body = json.dumps(data, indent=2, ensure_ascii=False).replace("</", "<\\/")
    return f'<script type="application/ld+json">\n{body}\n</script>'


def render_jsonld_skills(manifest):
    return item_list("Skillsmith agent skills", "/skills/", skills_only(manifest))


def render_jsonld_mods(manifest):
    return item_list("Skillsmith mods for Claude Code", "/mods/", mods_only(manifest))


REGIONS = {
    "skills": render_skills,
    "jump": render_jump,
    "mods": render_mods,
    "wall": render_wall,
    "workflows": render_workflows,
    "outcomes": render_outcomes,
    "flagships": render_flagships,
    "stats": render_stats,
    "jsonld-skills": render_jsonld_skills,
    "jsonld-mods": render_jsonld_mods,
}
INLINE = {"stats"}


def render(text, manifest):
    """Rewrite every known region the page carries; anything outside the markers is kept."""
    nl = "\r\n" if "\r\n" in text else "\n"
    for name in REGION_RE.findall(text):
        if name not in REGIONS:
            raise SystemExit(f"unknown generated region {name!r}")
        start, end = f"<!-- gen:{name}:start -->", f"<!-- gen:{name}:end -->"
        left = text.index(start) + len(start)
        right = text.index(end, left)
        body = REGIONS[name](manifest).replace("\n", nl)
        if name in INLINE:
            block = body
        else:
            indent = text[text.rfind("\n", 0, right) + 1:right]
            indent = indent if not indent.strip() else ""
            block = nl + body + nl + indent
        text = text[:left] + block + text[right:]
    return text


def flow_install(flow, manifest):
    by_name = {s["name"]: s for s in manifest["skills"]}
    rows = []
    for i, step in enumerate(flow["steps"], 1):
        for j, n in enumerate(step["skills"]):
            note = f"step {i}" + (", or the line above" if j else "") + (", optional" if step.get("optional") else "")
            rows.append((install_of(by_name[n]), note))
    width = max(len(cmd) for cmd, _ in rows)
    return "\n".join(f"{cmd.ljust(width)}  # {note}" for cmd, note in rows)


def flow_steps_html(flow, manifest):
    by_name = {s["name"]: s for s in manifest["skills"]}
    out = []
    for i, step in enumerate(flow["steps"], 1):
        kind = " · optional" if step.get("optional") else ""
        choice = " · pick one" if len(step["skills"]) > 1 else ""
        out.append(f'      <li class="step"><p class="step-n">Step {i}{kind}{choice}</p>')
        for n in step["skills"]:
            s = by_name[n]
            q = s.get("quality") or {}
            facts = ["v" + esc(q["version"]) if q.get("version") else "unversioned"]
            if s.get("tested"):
                facts.append("shown working " + esc(human_date(s["tested"]["date"])))
            if s.get("kind") == "mod":
                facts.append("Claude Code mod")
            out += [f'        <a class="step-skill" href="/{esc(n)}/">',
                    f'          <b>{esc(s["title"])}</b>',
                    f'          <span class="step-blurb">{esc(s["blurb"])}</span>',
                    f'          <span class="step-facts">{" · ".join(facts)}</span>',
                    '        </a>']
        out.append('      </li>')
    return "\n".join(out)


def render_flow_page(flow, manifest):
    flows = manifest.get("workflows", [])
    canonical = f"{skilllib.SITE}/workflows/{flow['slug']}/"
    others = "\n".join(f'      <li><a href="/workflows/{esc(f["slug"])}/">{esc(f["title"])}</a></li>'
                       for f in flows if f["id"] != flow["id"])
    note = f'    <p class="note">{esc(flow["note"])}</p>' if flow.get("note") else ""
    by_name = {s["name"]: s for s in manifest["skills"]}
    ld = {
        "@context": "https://schema.org",
        "@type": "HowTo",
        "name": flow["title"],
        "description": flow["summary"],
        "url": canonical,
        "step": [{"@type": "HowToStep", "position": i,
                  "name": " or ".join(by_name[n]["title"] for n in step["skills"]),
                  "url": f"{skilllib.SITE}/{step['skills'][0]}/"}
                 for i, step in enumerate(flow["steps"], 1)],
        "publisher": {"@type": "Organization", "name": "Caffeinity", "url": "https://caffeinity.com/"},
    }
    tokens = {
        "MARKER": FLOW_MARKER,
        "PAGE_TITLE": esc(f"{flow['title']}: an AI agent workflow | Skillsmith"),
        "DESCRIPTION": attr(flow["summary"]),
        "CANONICAL": attr(canonical),
        "JSON_LD": json.dumps(ld, indent=2, ensure_ascii=False).replace("</", "<\\/"),
        "BREW": esc(skilllib.brew_label(flow)),
        "TITLE": esc(flow["title"]),
        "SUMMARY": esc(flow["summary"]),
        "INSTALL": esc(flow_install(flow, manifest)),
        "INSTALL_ATTR": attr(flow_install(flow, manifest)),
        "STEPS": flow_steps_html(flow, manifest),
        "NOTE": note,
        "OTHERS": others,
    }
    text = FLOW_TEMPLATE.read_text(encoding="utf-8")
    for key, value in tokens.items():
        text = text.replace("{{" + key + "}}", value)
    leftover = sorted(set(re.findall(r"\{\{[A-Z_]+\}\}", text)))
    if leftover:
        raise SystemExit(f"workflow template tokens left unreplaced: {leftover}")
    return text


def expected_files(root, manifest):
    """{path: text} for every file this script owns all or part of."""
    root = Path(root)
    out = {}
    for rel in HUB_PAGES:
        path = root / rel
        with open(path, encoding="utf-8", newline="") as fh:
            out[path] = render(fh.read(), manifest)
    for flow in manifest.get("workflows", []):
        out[root / "workflows" / flow["slug"] / "index.html"] = render_flow_page(flow, manifest)
    return out


def stale_flow_dirs(root, manifest):
    """Generated workflow folders whose workflow is gone from the manifest."""
    slugs = {f["slug"] for f in manifest.get("workflows", [])}
    base = Path(root) / "workflows"
    return sorted(d for d in base.iterdir() if d.is_dir() and d.name not in slugs
                  and (d / "index.html").is_file()
                  and FLOW_MARKER in (d / "index.html").read_text(encoding="utf-8")) if base.is_dir() else []


def main(argv=None):
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument("--root", default=".")
    args = parser.parse_args(argv)
    root = Path(args.root)
    manifest = skilllib.load_manifest(root)
    skilllib.validate_manifest(manifest)
    expected = expected_files(root, manifest)
    if args.check:
        stale = []
        for path, text in expected.items():
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != text:
                stale.append(str(path.relative_to(root)))
                diff = difflib.unified_diff(current.splitlines(), text.splitlines(),
                                            fromfile=f"{path.relative_to(root)} (committed)",
                                            tofile=f"{path.relative_to(root)} (generated)", lineterm="")
                print("\n".join(list(diff)[:60]))
        stale += [f"{d.relative_to(root)} (workflow removed)" for d in stale_flow_dirs(root, manifest)]
        if stale:
            print("stale: " + ", ".join(stale) + "; run gen_home.py --write", file=sys.stderr)
            return 1
        print(f"hub pages and {len(manifest.get('workflows', []))} workflow pages are current")
        return 0
    for path, text in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    for d in stale_flow_dirs(root, manifest):
        shutil.rmtree(d)
    print(f"hub pages rewritten: {len(skills_only(manifest))} skills, {len(mods_only(manifest))} mods, "
          f"{len(manifest.get('workflows', []))} workflow pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
